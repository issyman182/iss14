/// <summary>
/// Cloud Station is generated by Tools/iss14_gen_cloud.py. Loading alone (GameMapsLoadableTest) doesn't prove the
/// generated wiring works, so this starts a round on it and checks power, piping and evac docking.
/// </summary>
[TestFixture]
public sealed class CloudStationTest : GameTest
{
    public override PoolSettings PoolSettings => new()
    {
        DummyTicker = true,
        Dirty = true,
    };

    [Test]
    public async Task PowerPipingAndEvacWork()
    {
        var pair = Pair;
        var server = pair.Server;
        var entMan = server.EntMan;
        var ticker = server.System<ServerGameTicker>();

        Assert.That(server.CfgMan.GetCVar(CCVars.GridFill), Is.False);
        server.CfgMan.SetCVar(CCVars.EmergencyShuttleEnabled, true);
        server.CfgMan.SetCVar(CCVars.GameDummyTicker, false);
        server.CfgMan.SetCVar(CCVars.GameMap, "Cloud");

        await server.WaitPost(() => ticker.RestartRound());
        await pair.RunTicksSync(25);
        Assert.That(ticker.RunLevel, Is.EqualTo(GameRunLevel.InRound));
        // Let the power net ramp up (SMES -> substation -> APC batteries).
        await pair.RunSeconds(15);

        var station = (Entity<StationCentcommComponent>) entMan.AllComponentsList<StationCentcommComponent>().Single();
        var data = entMan.GetComponent<StationDataComponent>(station);
        var grid = data.Grids.Single();

        // Power: every APC must be fed and (almost) every powered device on the grid must have power.
        var apcs = 0;
        var apcsPowered = 0;
        var receivers = 0;
        var receiversPowered = 0;
        var unpowered = new List<string>();
        await server.WaitAssertion(() =>
        {
            var apcQuery = entMan.EntityQueryEnumerator<ApcComponent, PowerNetworkBatteryComponent>();
            while (apcQuery.MoveNext(out var uid, out _, out var battery))
            {
                if (server.Transform(uid).GridUid != grid)
                    continue;
                apcs++;
                if (battery.CurrentReceiving > 0 || battery.NetworkBattery.CurrentStorage > 0)
                    apcsPowered++;
                else
                    unpowered.Add($"APC@{server.Transform(uid).LocalPosition}");
            }

            foreach (var (uid, receiver) in entMan.AllEntities<ApcPowerReceiverComponent>())
            {
                if (server.Transform(uid).GridUid != grid || !receiver.NeedsPower)
                    continue;
                receivers++;
                if (receiver.Powered)
                    receiversPowered++;
                else
                {
                    var ext = entMan.GetComponentOrNull<ExtensionCableReceiverComponent>(uid);
                    var prov = ext?.Provider != null ? server.Transform(ext.Provider.Value.Owner).LocalPosition.ToString() + "/" + entMan.GetComponent<MetaDataComponent>(ext.Provider.Value.Owner).EntityPrototype?.ID : "none";
                    unpowered.Add($"{entMan.GetComponent<MetaDataComponent>(uid).EntityPrototype?.ID}@{server.Transform(uid).LocalPosition} provider={prov} load={receiver.Load} connectable={ext?.Connectable}");
                }
            }
        });

        Assert.Multiple(() =>
        {
            Assert.That(apcs, Is.GreaterThan(20), "the station has an APC per room");
            Assert.That(apcsPowered, Is.EqualTo(apcs), $"every APC receives power from the substation: {string.Join(", ", unpowered.Where(u => u.StartsWith("APC")))}");
            Assert.That(receivers, Is.GreaterThan(100));
            Assert.That(receiversPowered, Is.GreaterThanOrEqualTo((int) (receivers * 0.95)),
                $"unpowered: {string.Join(", ", unpowered)}");
        });

        // Piping: every vent and scrubber sits on a pipe network with more than its own node.
        var lonely = new List<string>();
        var vents = 0;
        var pressurised = 0;
        await server.WaitAssertion(() =>
        {
            foreach (var (uid, nodes) in entMan.AllEntities<NodeContainerComponent>())
            {
                if (server.Transform(uid).GridUid != grid)
                    continue;
                var proto = entMan.GetComponent<MetaDataComponent>(uid).EntityPrototype?.ID ?? "";
                if (proto != "GasVentPump" && proto != "GasVentScrubber")
                    continue;
                vents++;
                var ok = nodes.Nodes.Values.Any(n => n.NodeGroup != null && n.NodeGroup.Nodes.Count > 1);
                if (!ok)
                    lonely.Add($"{proto} {server.Transform(uid).Coordinates}");
                if (proto == "GasVentPump" && nodes.Nodes.Values.OfType<Content.Server.NodeContainer.Nodes.PipeNode>().Any(n => n.Air.Pressure > 50f))
                    pressurised++;
            }
        });
        Assert.Multiple(() =>
        {
            Assert.That(vents, Is.GreaterThan(40));
            Assert.That(lonely, Is.Empty, "vents/scrubbers not connected to a pipe network");
            Assert.That(pressurised, Is.GreaterThan(20), "the air canisters pressurise the distribution loop");
        });

        // Evac: call the shuttle and make sure it docks at the station.
        var shuttleSys = server.System<ShuttleSystem>();
        var evacSys = server.System<EmergencyShuttleSystem>();
        evacSys.TransitTime = shuttleSys.DefaultTravelTime;
        server.CfgMan.SetCVar(CCVars.EmergencyShuttleDockTime, 60);

        var shuttleData = entMan.GetComponent<StationEmergencyShuttleComponent>(station);
        var shuttle = shuttleData.EmergencyShuttle!.Value;

        var dockSys = server.System<DockingSystem>();
        string diag = "";
        await server.WaitAssertion(() =>
        {
            var gridDocks = dockSys.GetDocks(grid);
            var shuttleDocks = dockSys.GetDocks(shuttle);
            diag = $"station docks={gridDocks.Count} [{string.Join("; ", gridDocks.Select(d => entMan.GetComponent<MetaDataComponent>(d).EntityPrototype?.ID + "@" + server.Transform(d).LocalPosition + " rot=" + server.Transform(d).LocalRotation + " anchored=" + server.Transform(d).Anchored))}] shuttle docks={shuttleDocks.Count} config={(dockSys.GetDockingConfig(shuttle, grid, "DockEmergency") != null)}";
        });
        TestContext.Out.WriteLine(diag);

        await pair.WaitCommand("callshuttle 0:02");
        await pair.RunSeconds(3);

        Assert.That(server.Transform(shuttle).MapUid, Is.EqualTo(server.Transform(grid).MapUid), "shuttle arrived at the station map");
        Assert.That(evacSys.EmergencyShuttleArrived, Is.True);

        var docked = 0;
        await server.WaitAssertion(() =>
        {
            foreach (var (uid, dock) in entMan.AllEntities<DockingComponent>())
            {
                if (server.Transform(uid).GridUid == shuttle && dock.Docked)
                    docked++;
            }
        });
        Assert.That(docked, Is.GreaterThan(0), "the emergency shuttle docked (not an emergency 'nearby' landing): " + diag);

        server.CfgMan.SetCVar(CCVars.GameMap, PoolManager.TestStation);
    }
}
