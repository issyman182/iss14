/// <summary>Cashier window: price list of the job's catalogs, the draft bill and the open bill.</summary>
[GenerateTypedNameReferences]
public sealed partial class CashRegisterWindow : FancyWindow
{
    /// <summary>(prototype, delta) — adds or removes items from the draft.</summary>
    public event Action<string, int>? OnAdjustDraft;
    /// <summary>(name, price, count) — adds a hand-written line.</summary>
    public event Action<string, int, int>? OnAddManual;
    public event Action<int>? OnRemoveLine;
    public event Action<string>? OnSetAccount;
    public event Action? OnClearDraft;
    public event Action? OnCreateBill;
    public event Action? OnCancelBill;
    public event Action<string, int?>? OnSetPrice;
    public event Action? OnRefresh;

    private List<CashRegisterItem> _items = new();
    private List<string> _catalogs = new();
    private List<CashRegisterAccount> _accounts = new();
    private CashRegisterBill _draft = new();
    private string _itemsSignature = string.Empty;

    // Catalogs hidden by the filter window (by localized name). Empty = no filter.
    private readonly HashSet<string> _hiddenCatalogs = new();
    private CashRegisterFilterWindow? _filterWindow;

    public CashRegisterWindow()
    {
        RobustXamlLoader.Load(this);

        Tabs.SetTabTitle(0, Loc.GetString("cash-register-tab-sale"));
        Tabs.SetTabTitle(1, Loc.GetString("cash-register-tab-prices"));

        // "Counter only" is the sensible default: the full catalog is long.
        NearbyOnly.Pressed = true;
        PricesNearbyOnly.Pressed = true;

        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
        CancelBillButton.OnPressed += _ => OnCancelBill?.Invoke();
        ClearDraftButton.OnPressed += _ => OnClearDraft?.Invoke();
        CreateBillButton.OnPressed += _ => OnCreateBill?.Invoke();

        SaleSearch.OnTextChanged += _ => BuildItems();
        PriceSearch.OnTextChanged += _ => BuildPrices();
        NearbyOnly.OnToggled += _ => BuildItems();
        PricesNearbyOnly.OnToggled += _ => BuildPrices();
        FilterButton.OnPressed += _ => OpenFilter();

        AccountOption.OnItemSelected += a =>
        {
            AccountOption.SelectId(a.Id);
            if (a.Id >= 0 && a.Id < _accounts.Count)
                OnSetAccount?.Invoke(_accounts[a.Id].Id);
        };

        ManualAddButton.OnPressed += _ => SubmitManual();
        ManualName.OnTextEntered += _ => SubmitManual();
        ManualPrice.OnTextEntered += _ => SubmitManual();

        OnClose += () => _filterWindow?.Close();
    }

    private void SubmitManual()
    {
        var name = ManualName.Text.Trim();
        if (name.Length == 0
            || !int.TryParse(ManualPrice.Text.Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture, out var price) || price <= 0)
            return;

        if (!int.TryParse(ManualCount.Text.Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture, out var count) || count <= 0)
            count = 1;

        OnAddManual?.Invoke(name, price, count);
        ManualName.Text = string.Empty;
        ManualPrice.Text = string.Empty;
        ManualCount.Text = "1";
    }

    public void SetState(CashRegisterBuiState state)
    {
        _items = state.Items;
        _catalogs = state.Catalogs;
        _accounts = state.Accounts;
        _draft = state.Draft;

        // Drop filter entries for catalogs the cashier no longer has.
        _hiddenCatalogs.RemoveWhere(c => !_catalogs.Contains(c));

        DepartmentLabel.Text = Loc.GetString("cash-register-department", ("department", state.Department), ("balance", state.DepartmentBalance));
        CommissionLabel.Text = Loc.GetString("cash-register-commission",
            ("commission", state.CommissionPercent.ToString("0.#", CultureInfo.InvariantCulture)));

        AccountOption.Visible = _accounts.Count > 1;
        AccountOption.Clear();
        for (var i = 0; i < _accounts.Count; i++)
        {
            AccountOption.AddItem(_accounts[i].Name, i);
            if (_accounts[i].Id == _draft.Account.Id)
                AccountOption.SelectId(i);
        }

        // Rows are only rebuilt when the list itself changed; a draft change just refreshes the counters.
        var signature = string.Join("|", _items.Select(i => $"{i.Prototype}:{i.Count}:{i.Price}:{i.Overridden}"));
        if (signature != _itemsSignature)
        {
            _itemsSignature = signature;
            BuildItems();
            BuildPrices();
        }
        else
        {
            UpdateCounters();
        }

        _filterWindow?.SetCatalogs(_catalogs, _hiddenCatalogs);
        UpdateFilterLabel();

        DraftLines.RemoveAllChildren();
        if (_draft.Lines.Count == 0)
        {
            DraftHeader.Text = Loc.GetString("cash-register-draft-empty");
            DraftTotal.Text = string.Empty;
        }
        else
        {
            DraftHeader.Text = Loc.GetString("cash-register-draft-header");
            for (var i = 0; i < _draft.Lines.Count; i++)
            {
                var line = _draft.Lines[i];
                var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
                row.AddChild(new Label
                {
                    Text = Loc.GetString("cash-register-bill-line", ("count", line.Count), ("name", line.Name), ("price", line.Price), ("total", line.Total)),
                    HorizontalExpand = true,
                    ClipText = true,
                });
                var index = i;
                var remove = new Button { Text = "×", MinWidth = 28 };
                remove.OnPressed += _ => OnRemoveLine?.Invoke(index);
                row.AddChild(remove);
                DraftLines.AddChild(row);
            }

            DraftTotal.Text = Loc.GetString("cash-register-selection-total", ("total", _draft.Total));
        }

        ClearDraftButton.Disabled = _draft.Lines.Count == 0;
        CreateBillButton.Disabled = _draft.Lines.Count == 0 || state.Bill != null;

        if (state.Bill is { } bill)
        {
            BillHeader.Text = Loc.GetString("cash-register-open-bill", ("total", bill.Total), ("cashier", bill.Cashier));
            BillLines.Text = string.Join("\n", bill.Lines.Select(l => Loc.GetString("cash-register-bill-line",
                ("count", l.Count), ("name", l.Name), ("price", l.Price), ("total", l.Total))));
            CancelBillButton.Visible = true;
        }
        else
        {
            BillHeader.Text = Loc.GetString("cash-register-no-open-bill");
            BillLines.Text = string.Empty;
            CancelBillButton.Visible = false;
        }

        MessageLabel.Text = state.Message;
    }

    #region Filter

    private void OpenFilter()
    {
        if (_filterWindow is { IsOpen: true })
        {
            _filterWindow.MoveToFront();
            return;
        }

        _filterWindow = new CashRegisterFilterWindow();
        _filterWindow.OnChanged += (catalog, shown) =>
        {
            if (shown)
                _hiddenCatalogs.Remove(catalog);
            else
                _hiddenCatalogs.Add(catalog);
            UpdateFilterLabel();
            BuildItems();
            BuildPrices();
        };
        _filterWindow.SetCatalogs(_catalogs, _hiddenCatalogs);
        _filterWindow.OpenCenteredLeft();
    }

    private void UpdateFilterLabel()
    {
        if (_hiddenCatalogs.Count == 0)
        {
            FilterLabel.Visible = false;
            return;
        }

        var shown = _catalogs.Where(c => !_hiddenCatalogs.Contains(c)).ToList();
        FilterLabel.Visible = true;
        FilterLabel.Text = shown.Count == 0
            ? Loc.GetString("cash-register-filter-none")
            : Loc.GetString("cash-register-filter-active", ("catalogs", string.Join(", ", shown)));
    }

    private bool PassesFilter(CashRegisterItem item) => !_hiddenCatalogs.Contains(item.Catalog);

    #endregion

    private int InDraft(CashRegisterItem item) => _draft.Lines.Where(l => l.Name == item.Name && l.Price == item.Price).Sum(l => l.Count);

    private static bool MatchesSearch(CashRegisterItem item, string search)
        => search.Length == 0
           || item.Name.Contains(search, StringComparison.OrdinalIgnoreCase)
           || item.Catalog.Contains(search, StringComparison.OrdinalIgnoreCase);

    private readonly Dictionary<string, (CashRegisterItem Item, Label Label)> _countLabels = new();

    private void BuildItems()
    {
        ItemsBox.RemoveAllChildren();
        _countLabels.Clear();

        var search = SaleSearch.Text.Trim();
        var shown = _items.Where(i => (!NearbyOnly.Pressed || i.Count > 0) && PassesFilter(i) && MatchesSearch(i, search)).ToList();

        if (shown.Count == 0)
        {
            ItemsBox.AddChild(new Label
            {
                Text = Loc.GetString(_items.Count == 0 ? "cash-register-no-items" : NearbyOnly.Pressed ? "cash-register-no-nearby" : "cash-register-no-matches"),
                StyleClasses = { "LabelSubText" },
            });
            return;
        }

        string? catalog = null;
        foreach (var item in shown)
        {
            if (item.Catalog != catalog)
            {
                catalog = item.Catalog;
                ItemsBox.AddChild(new Label { Text = catalog, StyleClasses = { "LabelHeading" }, Margin = new Thickness(0, 6, 0, 0) });
            }

            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 2, 0, 0) };
            row.AddChild(new Label { Text = item.Name, HorizontalExpand = true, ClipText = true });
            row.AddChild(new Label
            {
                Text = item.Count > 0
                    ? Loc.GetString("cash-register-item-info", ("count", item.Count), ("price", item.Price))
                    : Loc.GetString("cash-register-item-price", ("price", item.Price)),
                StyleClasses = { "LabelSubText" },
                MinWidth = 130,
                Align = Label.AlignMode.Right,
                Margin = new Thickness(0, 0, 6, 0),
            });

            var proto = item.Prototype;
            var available = item.Count;
            var minus = new Button { Text = "-", MinWidth = 28 };
            var countLabel = new Label { Text = InDraft(item).ToString(), MinWidth = 28, Align = Label.AlignMode.Center };
            var plus = new Button { Text = "+", MinWidth = 28 };

            minus.OnPressed += _ => OnAdjustDraft?.Invoke(proto, -1);
            plus.OnPressed += _ => OnAdjustDraft?.Invoke(proto, 1);
            row.AddChild(minus);
            row.AddChild(countLabel);
            row.AddChild(plus);

            if (available > 0)
            {
                var all = new Button { Text = Loc.GetString("cash-register-all"), Margin = new Thickness(4, 0, 0, 0), MinWidth = 40 };
                var snapshot = item;
                all.OnPressed += _ =>
                {
                    var delta = available - InDraft(snapshot);
                    if (delta > 0)
                        OnAdjustDraft?.Invoke(proto, delta);
                };
                row.AddChild(all);
            }
            else
            {
                row.AddChild(new Control { MinWidth = 44 });
            }

            _countLabels[proto] = (item, countLabel);
            ItemsBox.AddChild(row);
        }
    }

    private void UpdateCounters()
    {
        foreach (var (_, (item, label)) in _countLabels)
        {
            label.Text = InDraft(item).ToString();
        }
    }

    private void BuildPrices()
    {
        PricesBox.RemoveAllChildren();

        var search = PriceSearch.Text.Trim();
        var shown = _items.Where(i => (!PricesNearbyOnly.Pressed || i.Count > 0 || i.Overridden) && PassesFilter(i) && MatchesSearch(i, search)).ToList();

        if (shown.Count == 0)
        {
            PricesBox.AddChild(new Label
            {
                Text = Loc.GetString(_items.Count == 0 ? "cash-register-no-items" : PricesNearbyOnly.Pressed ? "cash-register-no-nearby" : "cash-register-no-matches"),
                StyleClasses = { "LabelSubText" },
            });
            return;
        }

        string? catalog = null;
        foreach (var item in shown)
        {
            if (item.Catalog != catalog)
            {
                catalog = item.Catalog;
                PricesBox.AddChild(new Label { Text = catalog, StyleClasses = { "LabelHeading" }, Margin = new Thickness(0, 6, 0, 0) });
            }

            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 2, 0, 0) };
            row.AddChild(new Label { Text = item.Name, HorizontalExpand = true, ClipText = true });

            var edit = new LineEdit { Text = item.Price.ToString(CultureInfo.InvariantCulture), MinWidth = 80 };
            var proto = item.Prototype;
            var current = item.Price;
            edit.OnTextEntered += a => Submit(proto, a.Text, current);
            edit.OnFocusExit += a => Submit(proto, a.Text, current);
            row.AddChild(edit);

            var reset = new Button
            {
                Text = Loc.GetString("cash-register-reset-price"),
                Margin = new Thickness(4, 0, 0, 0),
                Disabled = !item.Overridden,
            };
            reset.OnPressed += _ => OnSetPrice?.Invoke(proto, null);
            row.AddChild(reset);

            row.AddChild(new Label
            {
                Text = item.Overridden ? Loc.GetString("cash-register-default-price", ("price", item.DefaultPrice)) : string.Empty,
                StyleClasses = { "LabelSubText" },
                MinWidth = 90,
                Margin = new Thickness(6, 0, 0, 0),
            });

            PricesBox.AddChild(row);
        }
    }

    private void Submit(string proto, string text, int current)
    {
        if (!int.TryParse(text, NumberStyles.Integer, CultureInfo.InvariantCulture, out var price) || price < 0 || price == current)
            return;

        OnSetPrice?.Invoke(proto, price);
    }
}

/// <summary>Small window with one checkbox per catalog; unticked catalogs are hidden in the cashier window.</summary>
public sealed class CashRegisterFilterWindow : DefaultWindow
{
    /// <summary>(catalog name, shown)</summary>
    public event Action<string, bool>? OnChanged;

    private readonly BoxContainer _box;
    private bool _updating;

    public CashRegisterFilterWindow()
    {
        Title = Loc.GetString("cash-register-filter-title");
        MinSize = new System.Numerics.Vector2(240, 120);

        _box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(4) };
        var root = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical };
        root.AddChild(new Label { Text = Loc.GetString("cash-register-filter-hint"), StyleClasses = { "LabelSubText" } });
        root.AddChild(_box);
        Contents.AddChild(root);
    }

    public void SetCatalogs(List<string> catalogs, HashSet<string> hidden)
    {
        _updating = true;
        _box.RemoveAllChildren();
        foreach (var catalog in catalogs)
        {
            var check = new CheckBox { Text = catalog, Pressed = !hidden.Contains(catalog) };
            var name = catalog;
            check.OnToggled += a =>
            {
                if (!_updating)
                    OnChanged?.Invoke(name, a.Pressed);
            };
            _box.AddChild(check);
        }

        _updating = false;
    }
}
