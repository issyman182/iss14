// iss14: Economy
using System.Globalization;
using Content.Client.UserInterface.Controls;
using Content.Shared.Economy;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Economy;

[GenerateTypedNameReferences]
public sealed partial class AtmWindow : FancyWindow
{
    public event Action<int>? OnWithdraw;
    public event Action? OnDeposit;
    public event Action? OnVerify;

    public AtmWindow()
    {
        RobustXamlLoader.Load(this);

        WithdrawButton.OnPressed += _ => Withdraw();
        AmountEdit.OnTextEntered += _ => Withdraw();
        DepositButton.OnPressed += _ => OnDeposit?.Invoke();
        VerifyButton.OnPressed += _ => OnVerify?.Invoke();
    }

    private void Withdraw()
    {
        if (int.TryParse(AmountEdit.Text, NumberStyles.Integer, CultureInfo.InvariantCulture, out var amount) && amount > 0)
            OnWithdraw?.Invoke(amount);
        else
            MessageLabel.Text = Loc.GetString("atm-bad-amount");
    }

    public void SetState(AtmBoundUserInterfaceState state)
    {
        OwnerLabel.Text = state.HasCard ? state.OwnerName ?? string.Empty : Loc.GetString("atm-window-no-card");
        BalanceLabel.Text = state.HasCard
            ? Loc.GetString("atm-window-credits", ("amount", state.Balance))
            : "-";
        CashLabel.Text = state.CashInSlot > 0
            ? Loc.GetString("atm-window-credits", ("amount", state.CashInSlot))
            : Loc.GetString("atm-window-cash-empty");

        WithdrawButton.Disabled = !state.HasCard;
        DepositButton.Disabled = !state.HasCard || state.CashInSlot <= 0;
        VerifyButton.Disabled = !state.HasCard;

        var limit = state.WithdrawRemaining < 0
            ? Loc.GetString("atm-window-limit-none")
            : Loc.GetString("atm-window-limit", ("limit", state.WithdrawRemaining));
        var fee = state.FeePercent > 0
            ? " " + Loc.GetString("atm-window-fee", ("fee", state.FeePercent.ToString("0.##", CultureInfo.InvariantCulture)))
            : string.Empty;
        var fingerprint = state.FingerprintRequired ? " " + Loc.GetString("atm-window-fingerprint-required") : string.Empty;
        LimitLabel.Text = limit + fee + fingerprint;

        VerifyLabel.Text = state.Verify switch
        {
            AtmVerifyResult.Match => Loc.GetString("atm-window-verify-match"),
            AtmVerifyResult.Mismatch => Loc.GetString("atm-window-verify-mismatch"),
            AtmVerifyResult.Unknown => Loc.GetString("atm-window-verify-unknown"),
            _ => string.Empty,
        };

        MessageLabel.Text = state.Message;
    }
}
