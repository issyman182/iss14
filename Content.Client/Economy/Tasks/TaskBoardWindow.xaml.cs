using System.Globalization;
using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.Economy.Tasks;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Economy.Tasks;

[GenerateTypedNameReferences]
public sealed partial class TaskBoardWindow : FancyWindow
{
    public event Action<uint>? OnClaim;
    public event Action<uint>? OnAbandon;
    public event Action<uint>? OnConfirm;
    public event Action<uint>? OnCancel;
    public event Action<string, string, int>? OnCreate;

    public TaskBoardWindow()
    {
        RobustXamlLoader.Load(this);

        CreateButton.OnPressed += _ =>
        {
            if (!int.TryParse(RewardEdit.Text, NumberStyles.Integer, CultureInfo.InvariantCulture, out var reward))
                return;

            OnCreate?.Invoke(TitleEdit.Text, DescriptionEdit.Text, reward);
            TitleEdit.Text = string.Empty;
            DescriptionEdit.Text = string.Empty;
            RewardEdit.Text = string.Empty;
        };
    }

    public void SetState(TaskBoardBuiState state)
    {
        HeaderLabel.Text = Loc.GetString("task-board-header", ("department", state.Department), ("balance", state.DepartmentBalance));
        CreatePanel.Visible = state.IsHead;
        MessageLabel.Text = state.Message;

        TasksBox.RemoveAllChildren();
        if (state.Tasks.Count == 0)
        {
            TasksBox.AddChild(new Label { Text = Loc.GetString("task-board-empty"), StyleClasses = { "LabelSubText" } });
            return;
        }

        foreach (var task in state.Tasks.OrderBy(t => t.Status == DepartmentTaskStatus.Completed).ThenByDescending(t => t.Created))
        {
            var panel = new PanelContainer { StyleClasses = { "BackgroundDark" }, Margin = new Thickness(0, 0, 0, 4) };
            var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(6) };

            var header = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            var title = new Label { Text = task.Title, HorizontalExpand = true };
            if (task.Status == DepartmentTaskStatus.Completed)
                title.StyleClasses.Add("LabelSubText");
            else
                title.StyleClasses.Add("LabelKeyText");
            header.AddChild(title);
            header.AddChild(new Label { Text = Loc.GetString("task-board-reward-label", ("reward", task.Reward)), StyleClasses = { "LabelKeyText" } });
            box.AddChild(header);

            if (!string.IsNullOrEmpty(task.Description))
                box.AddChild(new Label { Text = task.Description, StyleClasses = { "LabelSubText" } });

            var statusText = task.Status switch
            {
                DepartmentTaskStatus.Open => Loc.GetString("task-board-status-open", ("issuer", task.Issuer)),
                DepartmentTaskStatus.Claimed => Loc.GetString("task-board-status-claimed", ("issuer", task.Issuer), ("name", task.ClaimedBy ?? "?")),
                _ => Loc.GetString("task-board-status-done", ("name", task.ClaimedBy ?? "?")),
            };
            if (task.Kind == DepartmentTaskKind.Delivery && task.Status != DepartmentTaskStatus.Completed)
                statusText += " " + Loc.GetString("task-board-status-delivery", ("progress", task.DeliverProgress), ("target", task.DeliverTarget));

            var footer = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 4, 0, 0) };
            footer.AddChild(new Label { Text = statusText, StyleClasses = { "LabelSubText" }, HorizontalExpand = true });

            var id = task.Id;
            if (task.Status == DepartmentTaskStatus.Open && state.IsMember)
                footer.AddChild(Button(Loc.GetString("task-board-claim"), () => OnClaim?.Invoke(id)));
            if (task.Status == DepartmentTaskStatus.Claimed)
                footer.AddChild(Button(Loc.GetString("task-board-abandon"), () => OnAbandon?.Invoke(id)));
            if (task.Status == DepartmentTaskStatus.Claimed && task.Kind == DepartmentTaskKind.Manual && state.IsHead)
                footer.AddChild(Button(Loc.GetString("task-board-confirm"), () => OnConfirm?.Invoke(id)));
            if (task.Status != DepartmentTaskStatus.Completed && state.IsHead)
                footer.AddChild(Button(Loc.GetString("task-board-remove"), () => OnCancel?.Invoke(id)));

            box.AddChild(footer);
            panel.AddChild(box);
            TasksBox.AddChild(panel);
        }
    }

    private static Button Button(string text, Action act)
    {
        var button = new Button { Text = text, Margin = new Thickness(4, 0, 0, 0) };
        button.OnPressed += _ => act();
        return button;
    }
}
