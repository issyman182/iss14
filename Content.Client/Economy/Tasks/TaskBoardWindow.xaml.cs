using System.Globalization;
using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.Economy.Tasks;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.Economy.Tasks;

/// <summary>
/// Task board window. Shows the tasks of the department the viewer picked (only departments they belong to are
/// offered); a viewer who belongs to none sees an access notice.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class TaskBoardWindow : FancyWindow
{
    public event Action<uint>? OnClaim;
    public event Action<uint>? OnAbandon;
    public event Action<uint>? OnConfirm;
    public event Action<uint>? OnCancel;
    /// <summary>(department, title, description, reward)</summary>
    public event Action<string, string, string, int>? OnCreate;

    private List<TaskBoardDepartment> _departments = new();
    private List<DepartmentTask> _tasks = new();
    private string? _selected;

    public TaskBoardWindow()
    {
        RobustXamlLoader.Load(this);

        DepartmentOption.OnItemSelected += a =>
        {
            DepartmentOption.SelectId(a.Id);
            if (a.Id >= 0 && a.Id < _departments.Count)
                _selected = _departments[a.Id].Id;
            Rebuild();
        };

        CreateButton.OnPressed += _ =>
        {
            if (_selected == null || !int.TryParse(RewardEdit.Text, NumberStyles.Integer, CultureInfo.InvariantCulture, out var reward))
                return;

            OnCreate?.Invoke(_selected, TitleEdit.Text, DescriptionEdit.Text, reward);
            TitleEdit.Text = string.Empty;
            DescriptionEdit.Text = string.Empty;
            RewardEdit.Text = string.Empty;
        };
    }

    /// <param name="departments">The viewer's own departments (already picked out of the state).</param>
    public void SetState(TaskBoardBuiState state, List<TaskBoardDepartment> departments)
    {
        _departments = departments;
        _tasks = state.Tasks;
        MessageLabel.Text = state.Message;

        if (_selected == null || _departments.All(d => d.Id != _selected))
            _selected = _departments.Count > 0 ? _departments[0].Id : null;

        DepartmentOption.Visible = _departments.Count > 1;
        DepartmentOption.Clear();
        for (var i = 0; i < _departments.Count; i++)
        {
            DepartmentOption.AddItem(_departments[i].Name, i);
            if (_departments[i].Id == _selected)
                DepartmentOption.SelectId(i);
        }

        Rebuild();
    }

    private void Rebuild()
    {
        TasksBox.RemoveAllChildren();

        var department = _departments.FirstOrDefault(d => d.Id == _selected);
        if (department == null)
        {
            HeaderLabel.Text = Loc.GetString("task-board-header-no-access");
            HintLabel.Text = Loc.GetString("task-board-no-access");
            CreatePanel.Visible = false;
            return;
        }

        HeaderLabel.Text = Loc.GetString("task-board-header", ("department", department.Name), ("balance", department.Balance));
        HintLabel.Text = Loc.GetString("task-board-hint");
        CreatePanel.Visible = department.IsHead;
        CreateHeading.Text = Loc.GetString("task-board-create-heading-department", ("department", department.Name));

        var tasks = _tasks.Where(t => t.Department.Id == department.Id).ToList();
        if (tasks.Count == 0)
        {
            TasksBox.AddChild(new Label { Text = Loc.GetString("task-board-empty"), StyleClasses = { "LabelSubText" } });
            return;
        }

        foreach (var task in tasks.OrderBy(t => t.Status == DepartmentTaskStatus.Completed).ThenByDescending(t => t.Created))
        {
            var panel = new PanelContainer { StyleClasses = { "BackgroundDark" }, Margin = new Thickness(0, 0, 0, 4) };
            var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(6) };

            var header = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            var title = new Label { Text = task.Title, HorizontalExpand = true };
            title.StyleClasses.Add(task.Status == DepartmentTaskStatus.Completed ? "LabelSubText" : "LabelKeyText");
            header.AddChild(title);
            header.AddChild(new Label { Text = Loc.GetString("task-board-reward-label", ("reward", task.Reward)), StyleClasses = { "LabelKeyText" } });
            box.AddChild(header);

            if (!string.IsNullOrEmpty(task.Description))
            {
                // RichTextLabel wraps long descriptions to the window width; a plain Label would run off the edge.
                var description = new RichTextLabel { HorizontalExpand = true, Margin = new Thickness(0, 2, 0, 0) };
                description.SetMessage(FormattedMessage.FromMarkupPermissive($"[color=#aaaaaa]{FormattedMessage.EscapeText(task.Description)}[/color]"));
                box.AddChild(description);
            }

            var statusText = task.Status switch
            {
                DepartmentTaskStatus.Open => Loc.GetString("task-board-status-open", ("issuer", task.Issuer)),
                DepartmentTaskStatus.Claimed => Loc.GetString("task-board-status-claimed", ("issuer", task.Issuer), ("name", task.ClaimedBy ?? "?")),
                _ => Loc.GetString("task-board-status-done", ("name", task.ClaimedBy ?? "?")),
            };
            if (task.Status != DepartmentTaskStatus.Completed && task.DeliverTarget > 0)
            {
                var key = task.Kind switch
                {
                    DepartmentTaskKind.Delivery => "task-board-status-delivery",
                    DepartmentTaskKind.Cleaning => "task-board-status-cleaning",
                    _ => task.Action switch
                    {
                        DepartmentTaskAction.HealDamage => "task-board-status-heal",
                        DepartmentTaskAction.Patrol => "task-board-status-patrol",
                        DepartmentTaskAction.Visit => "task-board-status-visit",
                        _ => "task-board-status-progress",
                    },
                };
                statusText += " " + Loc.GetString(key, ("progress", task.DeliverProgress), ("target", task.DeliverTarget));
            }

            var footer = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 4, 0, 0) };
            footer.AddChild(new Label { Text = statusText, StyleClasses = { "LabelSubText" }, HorizontalExpand = true, ClipText = true });

            var id = task.Id;
            if (task.Status == DepartmentTaskStatus.Open)
                footer.AddChild(Button(Loc.GetString("task-board-claim"), () => OnClaim?.Invoke(id)));
            if (task.Status == DepartmentTaskStatus.Claimed)
                footer.AddChild(Button(Loc.GetString("task-board-abandon"), () => OnAbandon?.Invoke(id)));
            if (task.Status == DepartmentTaskStatus.Claimed && task.Kind == DepartmentTaskKind.Manual && department.IsHead)
                footer.AddChild(Button(Loc.GetString("task-board-confirm"), () => OnConfirm?.Invoke(id)));
            if (task.Status != DepartmentTaskStatus.Completed && department.IsHead)
                footer.AddChild(Button(Loc.GetString("task-board-remove"), () => OnCancel?.Invoke(id)));

            box.AddChild(footer);
            panel.AddChild(box);
            TasksBox.AddChild(panel);
        }
    }

    private static Button Button(string text, Action act)
    {
        var button = new Button { Text = text, Margin = new Thickness(4, 0, 0, 0) };
        button.OnPressed += _ => act();
        return button;
    }
}
