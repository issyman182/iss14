// iss14: Economy
using System.Globalization;
using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.CriminalRecords;
using Content.Shared.Economy;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Economy;

[GenerateTypedNameReferences]
public sealed partial class FineTerminalWindow : FancyWindow
{
    public event Action<uint?>? OnSelectRecord;
    public event Action<uint, int, string>? OnIssue;
    public event Action<uint, uint>? OnWaive;
    public event Action<uint>? OnPayOwn;
    public event Action<uint>? OnPayClient;
    public event Action? OnFileMandate;

    private List<FineTerminalRecordEntry> _records = new();
    private uint? _selected;
    private bool _updating;

    public FineTerminalWindow()
    {
        RobustXamlLoader.Load(this);

        Tabs.SetTabTitle(0, Loc.GetString("fine-terminal-tab-own"));
        Tabs.SetTabTitle(1, Loc.GetString("fine-terminal-tab-lawyer"));
        Tabs.SetTabTitle(2, Loc.GetString("fine-terminal-tab-security"));

        FileMandateButton.OnPressed += _ => OnFileMandate?.Invoke();
        RecordSearch.OnTextChanged += _ => PopulateRecords();
        RecordList.OnItemSelected += args =>
        {
            if (_updating)
                return;

            var entry = (FineTerminalRecordEntry) RecordList[args.ItemIndex].Metadata!;
            OnSelectRecord?.Invoke(entry.Id);
        };
        IssueButton.OnPressed += _ =>
        {
            if (_selected is not { } record)
                return;

            if (!int.TryParse(AmountEdit.Text, NumberStyles.Integer, CultureInfo.InvariantCulture, out var amount))
                return;

            OnIssue?.Invoke(record, amount, ReasonEdit.Text);
            AmountEdit.Text = string.Empty;
            ReasonEdit.Text = string.Empty;
        };
    }

    public void SetState(FineTerminalBuiState state)
    {
        _updating = true;

        // Own fines
        CardLabel.Text = state.CardHolder != null
            ? Loc.GetString("fine-terminal-card", ("name", state.CardHolder), ("total", state.OwnFines.Where(f => !f.Paid).Sum(f => f.Amount)))
            : Loc.GetString("fine-terminal-no-card-inserted");
        BuildFines(OwnFinesBox, state.OwnFines, state.CardHolder != null, Loc.GetString("fine-terminal-pay"), fine => OnPayOwn?.Invoke(fine.Id), null);

        // Lawyer
        MandateLabel.Text = state.MandateStatus ?? Loc.GetString("fine-terminal-no-mandate-paper");
        FileMandateButton.Disabled = state.MandateStatus == null;
        ClientLabel.Text = state.IsLawyer
            ? state.ClientName != null
                ? Loc.GetString("fine-terminal-client", ("name", state.ClientName), ("fee", state.LawyerFeePercent.ToString("0.#", CultureInfo.InvariantCulture)))
                : Loc.GetString("fine-terminal-no-client")
            : Loc.GetString("fine-terminal-not-lawyer-card");
        BuildFines(ClientFinesBox, state.ClientFines, state.IsLawyer && state.ClientName != null, Loc.GetString("fine-terminal-pay-client"), fine => OnPayClient?.Invoke(fine.Id), null);

        // Security
        Tabs.SetTabVisible(2, state.CanIssue);
        _records = state.Records;
        _selected = state.SelectedRecord;
        PopulateRecords();
        SelectedLabel.Text = state.SelectedName != null
            ? Loc.GetString("fine-terminal-selected", ("name", state.SelectedName))
            : Loc.GetString("fine-terminal-no-selection");
        IssueButton.Disabled = state.SelectedRecord == null;
        var selected = state.SelectedRecord;
        BuildFines(SelectedFinesBox, state.SelectedFines, selected != null, Loc.GetString("fine-terminal-waive"),
            fine => { if (selected is { } r) OnWaive?.Invoke(r, fine.Id); }, null);

        MessageLabel.Text = state.Message;
        _updating = false;
    }

    private void PopulateRecords()
    {
        _updating = true;
        RecordList.Clear();
        var filter = RecordSearch.Text.Trim();
        foreach (var record in _records)
        {
            if (filter.Length > 0 && !record.Name.Contains(filter, StringComparison.OrdinalIgnoreCase))
                continue;

            var text = record.OpenTotal > 0
                ? Loc.GetString("fine-terminal-record-open", ("name", record.Name), ("total", record.OpenTotal))
                : record.Name;
            var item = RecordList.AddItem(text);
            item.Metadata = record;
            if (record.Id == _selected)
                item.Selected = true;
        }
        _updating = false;
    }

    private void BuildFines(BoxContainer box, List<CriminalFine> fines, bool canAct, string actionText, Action<CriminalFine> action, string? empty)
    {
        box.RemoveAllChildren();

        if (fines.Count == 0)
        {
            box.AddChild(new Label { Text = empty ?? Loc.GetString("fine-terminal-no-fines"), StyleClasses = { "LabelSubText" } });
            return;
        }

        foreach (var fine in fines.OrderBy(f => f.Paid).ThenByDescending(f => f.IssuedAt))
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 2, 0, 0) };
            var text = fine.Paid
                ? Loc.GetString("fine-terminal-fine-paid", ("amount", fine.OriginalAmount), ("reason", fine.Reason), ("by", fine.PaidBy ?? "?"))
                : Loc.GetString("fine-terminal-fine-open", ("amount", fine.Amount), ("reason", fine.Reason), ("issuer", fine.IssuerName),
                    ("time", fine.IssuedAt.ToString(@"hh\:mm")));
            var label = new Label { Text = text, HorizontalExpand = true };
            if (fine.Paid)
                label.StyleClasses.Add("LabelSubText");
            row.AddChild(label);

            if (!fine.Paid && canAct)
            {
                var button = new Button { Text = actionText };
                var f = fine;
                button.OnPressed += _ => action(f);
                row.AddChild(button);
            }

            box.AddChild(row);
        }
    }
}
