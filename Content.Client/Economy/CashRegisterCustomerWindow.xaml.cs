using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.Economy;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Economy;

/// <summary>What a customer sees when clicking a cash register: the open bill and a pay button.</summary>
[GenerateTypedNameReferences]
public sealed partial class CashRegisterCustomerWindow : FancyWindow
{
    public event Action? OnPay;

    public CashRegisterCustomerWindow()
    {
        RobustXamlLoader.Load(this);
        PayButton.OnPressed += _ => OnPay?.Invoke();
    }

    public void SetState(CashRegisterCustomerBuiState state)
    {
        DepartmentLabel.Text = Loc.GetString("cash-register-customer-department", ("department", state.Department));

        if (state.Bill is { } bill)
        {
            BillHeader.Text = Loc.GetString("cash-register-customer-bill", ("cashier", bill.Cashier));
            BillLines.Text = string.Join("\n", bill.Lines.Select(l => Loc.GetString("cash-register-bill-line",
                ("count", l.Count), ("name", l.Name), ("price", l.Price), ("total", l.Total))));
            TotalLabel.Text = Loc.GetString("cash-register-customer-total", ("total", bill.Total));
            PayButton.Disabled = false;
            PayButton.Text = Loc.GetString("cash-register-pay-card-total", ("total", bill.Total));
        }
        else
        {
            BillHeader.Text = Loc.GetString("cash-register-customer-no-bill");
            BillLines.Text = string.Empty;
            TotalLabel.Text = string.Empty;
            PayButton.Disabled = true;
            PayButton.Text = Loc.GetString("cash-register-pay-card");
        }

        MessageLabel.Text = state.Message;
    }
}
