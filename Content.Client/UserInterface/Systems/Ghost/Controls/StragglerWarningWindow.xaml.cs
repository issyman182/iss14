using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.UserInterface.Systems.Ghost.Controls;

[GenerateTypedNameReferences]
public sealed partial class StragglerWarningWindow : DefaultWindow
{
    public event Action? Confirmed;

    public StragglerWarningWindow()
    {
        RobustXamlLoader.Load(this);

        WarningLabel.SetMessage(FormattedMessage.FromMarkupPermissive(
            Loc.GetString("ghost-gui-straggler-warning")));
        ConfirmButton.OnPressed += _ =>
        {
            Confirmed?.Invoke();
            Close();
        };
        CancelButton.OnPressed += _ => Close();
    }
}
