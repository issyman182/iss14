using System.Globalization;
using Content.Client.UserInterface.Controls;
using Content.Shared.Administration;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Administration.UI.EntityFinder;

/// <summary>Admin window listing entities with their grid/world positions and a teleport button per row.</summary>
[GenerateTypedNameReferences]
public sealed partial class EntityFinderWindow : FancyWindow
{
    /// <summary>(search, category, radius, same map only)</summary>
    public event Action<string, EntityFinderCategory, float, bool>? OnSearch;
    public event Action<NetEntity>? OnTeleport;

    private static readonly EntityFinderCategory[] Categories = Enum.GetValues<EntityFinderCategory>();

    public EntityFinderWindow()
    {
        RobustXamlLoader.Load(this);

        for (var i = 0; i < Categories.Length; i++)
            CategoryOption.AddItem(Loc.GetString($"entity-finder-category-{Categories[i].ToString().ToLowerInvariant()}"), i);
        CategoryOption.SelectId(0);
        CategoryOption.OnItemSelected += a =>
        {
            CategoryOption.SelectId(a.Id);
            Search();
        };

        SearchButton.OnPressed += _ => Search();
        SearchEdit.OnTextEntered += _ => Search();
        RadiusEdit.OnTextEntered += _ => Search();
        SameMapCheck.OnToggled += _ => Search();
    }

    private void Search()
    {
        var category = Categories[Math.Clamp(CategoryOption.SelectedId, 0, Categories.Length - 1)];
        var radius = float.TryParse(RadiusEdit.Text.Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out var r) && r > 0 ? r : 0f;
        OnSearch?.Invoke(SearchEdit.Text, category, radius, SameMapCheck.Pressed);
    }

    public void SetState(EntityFinderEuiState state)
    {
        AdminLabel.Text = state.AdminPosition;
        CountLabel.Text = state.Total > state.Rows.Count
            ? Loc.GetString("entity-finder-count-cut", ("shown", state.Rows.Count), ("total", state.Total))
            : Loc.GetString("entity-finder-count", ("total", state.Total));
        StatusLabel.Text = state.Status;

        RowsBox.RemoveAllChildren();
        foreach (var row in state.Rows)
        {
            var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 1, 0, 0) };

            var name = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
            name.AddChild(new Label { Text = row.Anchored ? Loc.GetString("entity-finder-name-anchored", ("name", row.Name)) : row.Name, ClipText = true });
            name.AddChild(new Label { Text = $"{row.Prototype} · {row.Entity}", StyleClasses = { "LabelSubText" }, ClipText = true });
            box.AddChild(name);

            box.AddChild(new Label { Text = row.GridPosition, MinWidth = 130, VerticalAlignment = VAlignment.Center });
            box.AddChild(new Label { Text = $"{row.WorldPosition} (map {row.MapId})", MinWidth = 150, VerticalAlignment = VAlignment.Center });
            box.AddChild(new Label
            {
                Text = row.Distance < 0 ? Loc.GetString("entity-finder-other-map") : Loc.GetString("entity-finder-distance", ("tiles", row.Distance.ToString("0.#", CultureInfo.InvariantCulture))),
                MinWidth = 80,
                VerticalAlignment = VAlignment.Center,
            });

            var entity = row.Entity;
            var teleport = new Button { Text = Loc.GetString("entity-finder-teleport"), MinWidth = 90 };
            teleport.OnPressed += _ => OnTeleport?.Invoke(entity);
            box.AddChild(teleport);

            RowsBox.AddChild(box);
        }
    }
}
