using System.Globalization;
using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.Administration;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Administration.UI.MoneyConfig;

/// <summary>
/// Economy config window. The settings tab is built from the server's entry list, so a new CVar only needs a row
/// in <c>MoneyConfigEui.Fields</c> and a loc string; the salary tab lists every job with its per-round base.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class MoneyConfigWindow : FancyWindow
{
    public event Action<string, string>? OnSet;
    public event Action<string, string>? OnSetSalary;
    public event Action<string, string>? OnSetPrice;

    private bool _updating;
    private readonly Dictionary<string, Control> _editors = new();
    private readonly Dictionary<string, (LineEdit Edit, Button Reset, Label Hint)> _salaryRows = new();
    private readonly Dictionary<string, string> _salaryValues = new();
    private bool _built;

    private List<MoneyPriceRow> _prices = new();
    private readonly Dictionary<string, string> _priceValues = new();
    private bool _canEdit;

    public MoneyConfigWindow()
    {
        RobustXamlLoader.Load(this);
        Tabs.SetTabTitle(0, Loc.GetString("money-config-tab-settings"));
        Tabs.SetTabTitle(1, Loc.GetString("money-config-tab-salaries"));
        Tabs.SetTabTitle(2, Loc.GetString("money-config-tab-prices"));

        PriceSearch.OnTextChanged += _ => BuildPrices();
        PriceOverriddenOnly.OnToggled += _ => BuildPrices();
    }

    public void SetState(MoneyConfigEuiState state)
    {
        _updating = true;

        if (!_built || _editors.Count != state.Entries.Count || _salaryRows.Count != state.Salaries.Count)
            Build(state);

        foreach (var entry in state.Entries)
        {
            if (!_editors.TryGetValue(entry.Key, out var control))
                continue;

            switch (control)
            {
                case CheckBox check:
                    check.Pressed = bool.TryParse(entry.Value, out var b) && b;
                    check.Disabled = !state.CanEdit;
                    break;
                case LineEdit edit:
                    if (!edit.HasKeyboardFocus())
                        edit.Text = entry.Value;
                    edit.Editable = state.CanEdit;
                    break;
            }
        }

        foreach (var row in state.Salaries)
        {
            if (!_salaryRows.TryGetValue(row.JobId, out var controls))
                continue;

            var text = row.Salary.ToString(CultureInfo.InvariantCulture);
            _salaryValues[row.JobId] = text;
            if (!controls.Edit.HasKeyboardFocus())
                controls.Edit.Text = text;
            controls.Edit.Editable = state.CanEdit;
            controls.Reset.Disabled = !state.CanEdit || !row.Overridden;
            controls.Hint.Text = row.Overridden
                ? Loc.GetString("money-config-salary-default-hint", ("default", row.DefaultSalary))
                : string.Empty;
        }

        _canEdit = state.CanEdit;
        var priceSignature = string.Join("|", state.Prices.Select(p => $"{p.Prototype}:{p.Price}:{p.Overridden}"));
        if (priceSignature != _priceSignature)
        {
            _priceSignature = priceSignature;
            _prices = state.Prices;
            BuildPrices();
        }

        StatusLabel.Text = state.Status;
        _updating = false;
    }

    private string _priceSignature = string.Empty;

    /// <summary>Default price table of the cash register catalogs, filtered by the search box.</summary>
    private void BuildPrices()
    {
        _updating = true;
        PricesBox.RemoveAllChildren();
        _priceValues.Clear();

        var search = PriceSearch.Text.Trim();
        var shown = _prices
            .Where(p => !PriceOverriddenOnly.Pressed || p.Overridden)
            .Where(p => search.Length == 0
                        || p.Name.Contains(search, StringComparison.OrdinalIgnoreCase)
                        || p.Catalog.Contains(search, StringComparison.OrdinalIgnoreCase)
                        || p.Prototype.Contains(search, StringComparison.OrdinalIgnoreCase))
            .OrderBy(p => p.Catalog, StringComparer.OrdinalIgnoreCase)
            .ThenBy(p => p.Name, StringComparer.OrdinalIgnoreCase)
            .ToList();

        if (shown.Count == 0)
            PricesBox.AddChild(new Label { Text = Loc.GetString("money-config-prices-empty"), StyleClasses = { "LabelSubText" } });

        string? catalog = null;
        foreach (var price in shown)
        {
            if (price.Catalog != catalog)
            {
                catalog = price.Catalog;
                PricesBox.AddChild(new Label
                {
                    Text = catalog,
                    StyleClasses = { "LabelHeading" },
                    Margin = new Thickness(0, PricesBox.ChildCount == 0 ? 0 : 10, 0, 0),
                });
            }

            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 2, 0, 0) };
            row.AddChild(new Label { Text = price.Name, HorizontalExpand = true, ClipText = true, ToolTip = price.Prototype });
            var text = price.Price.ToString(CultureInfo.InvariantCulture);
            _priceValues[price.Prototype] = text;
            var edit = new LineEdit { MinWidth = 90, Text = text, Editable = _canEdit };
            var proto = price.Prototype;
            edit.OnTextEntered += a => SetPrice(proto, a.Text);
            edit.OnFocusExit += a => SetPrice(proto, a.Text);
            row.AddChild(edit);
            var reset = new Button { Text = Loc.GetString("money-config-salary-reset"), Margin = new Thickness(6, 0, 0, 0), Disabled = !_canEdit || !price.Overridden };
            reset.OnPressed += _ => SetPrice(proto, string.Empty);
            row.AddChild(reset);
            row.AddChild(new Label
            {
                Text = price.Overridden ? Loc.GetString("money-config-prices-appraised-hint", ("price", price.AppraisedPrice)) : string.Empty,
                StyleClasses = { "LabelSubText" },
                MinWidth = 110,
                Margin = new Thickness(6, 0, 0, 0),
            });
            PricesBox.AddChild(row);
        }

        _updating = false;
    }

    private void SetPrice(string proto, string value)
    {
        if (_updating)
            return;

        if (value != string.Empty && _priceValues.TryGetValue(proto, out var known) && known == value.Trim())
            return;

        OnSetPrice?.Invoke(proto, value);
    }

    private void Build(MoneyConfigEuiState state)
    {
        _built = true;
        _editors.Clear();
        _salaryRows.Clear();
        SettingsBox.RemoveAllChildren();
        SalaryBox.RemoveAllChildren();

        string? section = null;
        foreach (var entry in state.Entries)
        {
            if (entry.Section != section)
            {
                section = entry.Section;
                SettingsBox.AddChild(new Label
                {
                    Text = section,
                    StyleClasses = { "LabelHeading" },
                    Margin = new Thickness(0, SettingsBox.ChildCount == 0 ? 0 : 10, 0, 0),
                });
            }

            if (entry.Kind == MoneyConfigKind.Toggle)
            {
                var check = new CheckBox { Text = entry.Label };
                var key = entry.Key;
                check.OnToggled += a => Set(key, a.Pressed.ToString());
                SettingsBox.AddChild(check);
                _editors[entry.Key] = check;
                continue;
            }

            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 4, 0, 0) };
            row.AddChild(new Label { Text = entry.Label, MinWidth = 300 });
            var edit = new LineEdit { MinWidth = 120 };
            var k = entry.Key;
            edit.OnTextEntered += a => Set(k, a.Text);
            edit.OnFocusExit += a => Set(k, a.Text);
            row.AddChild(edit);
            if (entry.Kind == MoneyConfigKind.Percent)
                row.AddChild(new Label { Text = "%", Margin = new Thickness(4, 0, 0, 0) });
            SettingsBox.AddChild(row);
            _editors[entry.Key] = edit;
        }

        string? department = null;
        foreach (var salary in state.Salaries)
        {
            if (salary.Department != department)
            {
                department = salary.Department;
                SalaryBox.AddChild(new Label
                {
                    Text = string.IsNullOrEmpty(department) ? Loc.GetString("money-config-salary-no-department") : department,
                    StyleClasses = { "LabelHeading" },
                    Margin = new Thickness(0, SalaryBox.ChildCount == 0 ? 0 : 10, 0, 0),
                });
            }

            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 2, 0, 0) };
            row.AddChild(new Label { Text = salary.JobName, MinWidth = 220 });
            var edit = new LineEdit { MinWidth = 90 };
            var job = salary.JobId;
            edit.OnTextEntered += a => SetSalary(job, a.Text);
            edit.OnFocusExit += a => SetSalary(job, a.Text);
            row.AddChild(edit);
            var reset = new Button { Text = Loc.GetString("money-config-salary-reset"), Margin = new Thickness(6, 0, 0, 0) };
            reset.OnPressed += _ => SetSalary(job, string.Empty);
            row.AddChild(reset);
            var hint = new Label { StyleClasses = { "LabelSubText" }, Margin = new Thickness(6, 0, 0, 0) };
            row.AddChild(hint);
            SalaryBox.AddChild(row);
            _salaryRows[salary.JobId] = (edit, reset, hint);
        }
    }

    private void Set(string key, string value)
    {
        if (!_updating)
            OnSet?.Invoke(key, value);
    }

    private void SetSalary(string job, string value)
    {
        if (_updating)
            return;

        // Losing focus without edits is not a change (it would otherwise create an override equal to the default).
        if (value != string.Empty && _salaryValues.TryGetValue(job, out var known) && known == value.Trim())
            return;

        OnSetSalary?.Invoke(job, value);
    }
}
