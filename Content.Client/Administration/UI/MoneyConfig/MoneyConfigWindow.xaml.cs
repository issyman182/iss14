using System.Globalization;
using Content.Client.UserInterface.Controls;
using Content.Shared.Administration;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Administration.UI.MoneyConfig;

[GenerateTypedNameReferences]
public sealed partial class MoneyConfigWindow : FancyWindow
{
    public event Action<MoneyConfigField, string>? OnSet;

    private bool _updating;

    public MoneyConfigWindow()
    {
        RobustXamlLoader.Load(this);

        SalaryEnabledCheck.OnToggled += a => Set(MoneyConfigField.SalaryEnabled, a.Pressed.ToString());
        FingerprintCheck.OnToggled += a => Set(MoneyConfigField.AtmRequireFingerprint, a.Pressed.ToString());
        VendingPricesCheck.OnToggled += a => Set(MoneyConfigField.VendingPrices, a.Pressed.ToString());

        Bind(MaxBalanceEdit, MoneyConfigField.MaxBalance);
        Bind(SalaryDefaultEdit, MoneyConfigField.SalaryDefaultPerHour);
        Bind(SalaryMultiplierEdit, MoneyConfigField.SalaryMultiplier);
        Bind(WithdrawLimitEdit, MoneyConfigField.AtmWithdrawLimit);
        Bind(FeeEdit, MoneyConfigField.AtmFeePercent);
        Bind(VendingMultiplierEdit, MoneyConfigField.VendingPriceMultiplier);
        Bind(ChipRateEdit, MoneyConfigField.ChipRate);
    }

    private void Bind(LineEdit edit, MoneyConfigField field)
    {
        edit.OnTextEntered += a => Set(field, a.Text);
        edit.OnFocusExit += a => Set(field, a.Text);
    }

    private void Set(MoneyConfigField field, string value)
    {
        if (!_updating)
            OnSet?.Invoke(field, value);
    }

    // Don't overwrite a field the user is currently editing.
    private static void SetText(LineEdit edit, string value)
    {
        if (!edit.HasKeyboardFocus())
            edit.Text = value;
    }

    public void SetState(MoneyConfigEuiState state)
    {
        _updating = true;

        SalaryEnabledCheck.Pressed = state.SalaryEnabled;
        FingerprintCheck.Pressed = state.AtmRequireFingerprint;
        VendingPricesCheck.Pressed = state.VendingPrices;

        SetText(MaxBalanceEdit, state.MaxBalance.ToString(CultureInfo.InvariantCulture));
        SetText(SalaryDefaultEdit, state.SalaryDefaultPerHour.ToString(CultureInfo.InvariantCulture));
        SetText(SalaryMultiplierEdit, state.SalaryMultiplier.ToString("0.##", CultureInfo.InvariantCulture));
        SetText(WithdrawLimitEdit, state.AtmWithdrawLimit.ToString(CultureInfo.InvariantCulture));
        SetText(FeeEdit, state.AtmFeePercent.ToString("0.##", CultureInfo.InvariantCulture));
        SetText(VendingMultiplierEdit, state.VendingPriceMultiplier.ToString("0.##", CultureInfo.InvariantCulture));
        SetText(ChipRateEdit, state.ChipRate.ToString(CultureInfo.InvariantCulture));

        SalaryEnabledCheck.Disabled = FingerprintCheck.Disabled = VendingPricesCheck.Disabled = !state.CanEdit;
        MaxBalanceEdit.Editable = SalaryDefaultEdit.Editable = SalaryMultiplierEdit.Editable = state.CanEdit;
        WithdrawLimitEdit.Editable = FeeEdit.Editable = VendingMultiplierEdit.Editable = ChipRateEdit.Editable = state.CanEdit;

        StatusLabel.Text = state.Status;

        _updating = false;
    }
}
